class Personaje:
    def __init__(self, id, nombre, nivel, exp, oro, vida_actual, id_raza, id_clase):
        self.id = id
        self.nombre = nombre
        self.nivel = nivel
        self.exp = exp
        self.oro = oro
        self.vida_actual = vida_actual
        self.id_raza = id_raza
        self.id_clase = id_clase